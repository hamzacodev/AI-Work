"""Builds the measured tables in docs/TOKEN_USAGE.md from the real usage logs. Run from backend/ after scripts/measure_tokens.py:

    uv run python scripts/token_report.py

It reads data/llm_usage_<label>.jsonl (one line per model call) and data/token_run_<label>.json (totals per scenario). It
rewrites only the block between the TOKEN-REPORT markers, so the analysis text around it is never touched. Nothing here is typed
by hand: every number comes from a recorded call.
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
DOC = ROOT.parent / "docs" / "TOKEN_USAGE.md"
START, END = "<!-- TOKEN-REPORT:START -->", "<!-- TOKEN-REPORT:END -->"

# If the same calls were paid for on Groq at list price (US dollars per 1M tokens: input, output). Local Ollama costs nothing.
GROQ = {"main": ("openai/gpt-oss-120b", 0.15, 0.60), "fast": ("openai/gpt-oss-20b", 0.075, 0.30)}


def load(label: str) -> list[dict]:
    p = DATA / f"llm_usage_{label}.jsonl"
    return [json.loads(line) for line in p.read_text().splitlines() if line.strip()] if p.exists() else []


def groq_cost(recs: list[dict]) -> float:
    total = 0.0
    for r in recs:
        _, pin, pout = GROQ[r["role"]]
        total += (r["prompt_tokens"] * pin + r["completion_tokens"] * pout) / 1_000_000
    return total


def sums(recs: list[dict]) -> dict:
    return {
        "calls": len(recs), "prompt": sum(r["prompt_tokens"] for r in recs), "completion": sum(r["completion_tokens"] for r in recs),
        "total": sum(r["total_tokens"] for r in recs), "cost": groq_cost(recs), "seconds": sum(r["latency_ms"] for r in recs) / 1000,
    }


def avg(xs: list[float]) -> int:
    return round(sum(xs) / len(xs)) if xs else 0


def per_call_table(recs: list[dict]) -> list[str]:
    groups: dict[tuple[str, str, str], list[dict]] = defaultdict(list)
    for r in recs:
        groups[(r["agent"], r["purpose"], r["role"])].append(r)
    rows = [
        ("| Agent | Purpose | Role | Calls | Input (avg) | Output (avg) | Total (avg) | System~ | Schema~ | Data~ | History~ | Retry~ | Cached "
         "| Latency (avg, includes waiting for a model slot) |"),
        "|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|",
    ]
    for (agent, purpose, role), rs in sorted(groups.items(), key=lambda kv: -sum(r["total_tokens"] for r in kv[1])):
        cached = "not reported" if all(r["cached_tokens"] is None for r in rs) else str(sum(r["cached_tokens"] or 0 for r in rs))
        rows.append(
            f"| {agent} | {purpose} | {role} | {len(rs)} | {avg([r['prompt_tokens'] for r in rs])} | {avg([r['completion_tokens'] for r in rs])} | "
            f"{avg([r['total_tokens'] for r in rs])} | {avg([r['system_tokens_est'] for r in rs])} | {avg([r['schema_tokens_est'] for r in rs])} | "
            f"{avg([r['user_tokens_est'] for r in rs])} | {avg([r['history_tokens_est'] for r in rs])} | {avg([r['retry_tokens_est'] for r in rs])} | "
            f"{cached} | {avg([r['latency_ms'] for r in rs]) / 1000:.1f} s |"
        )
    return rows


def pct(old: float, new: float) -> str:
    return "n/a" if not old else f"{(new - old) / old * 100:+.1f}%"


def build() -> str:
    labels = sorted(p.stem.removeprefix("llm_usage_") for p in DATA.glob("llm_usage_*.jsonl"))
    out = [START, "", "_Generated by `scripts/token_report.py` from the recorded model calls. Do not edit by hand._", ""]
    if not labels:
        out += ["No measurement has been recorded yet. Run `scripts/measure_tokens.py --label before`.", "", END]
        return "\n".join(out)

    for label in labels:
        recs = load(label)
        run = json.loads((DATA / f"token_run_{label}.json").read_text()) if (DATA / f"token_run_{label}.json").exists() else {}
        s = sums(recs)
        out += [f"### Measurement: {label}", ""]
        if run:
            out += [f"Provider **{run['provider']}**, main model **{run['model_main']}**, fast model **{run['model_fast']}**. Local Ollama calls cost nothing; the cost column below is what the same tokens would cost at Groq list price.", ""]
        out += ["| Scenario | Calls | Input tokens | Output tokens | Total tokens | Wall time |", "|---|---:|---:|---:|---:|---:|"]
        for name, sc in (run.get("scenarios") or {}).items():
            out.append(f"| {name} | {sc['calls']} | {sc['prompt']:,} | {sc['completion']:,} | {sc['total']:,} | {sc['seconds']} s |")
        out += [f"| **All** | **{s['calls']}** | **{s['prompt']:,}** | **{s['completion']:,}** | **{s['total']:,}** | |", ""]
        out += ["**Every kind of call** (the biggest token users first; `~` means an estimate: the host reports only the total, so the split into system, schema, data, history and retry is by share of characters):", ""]
        out += per_call_table(recs) + [""]
        by_agent: dict[str, list[dict]] = defaultdict(list)
        for r in recs:
            by_agent[r["agent"]].append(r)
        out += ["**By agent:**", "", "| Agent | Calls | Input | Output | Total | Share of all tokens | At Groq list price |", "|---|---:|---:|---:|---:|---:|---:|"]
        for agent, rs in sorted(by_agent.items(), key=lambda kv: -sum(r["total_tokens"] for r in kv[1])):
            t = sums(rs)
            out.append(f"| {agent} | {t['calls']} | {t['prompt']:,} | {t['completion']:,} | {t['total']:,} | {t['total'] / max(s['total'], 1) * 100:.0f}% | ${t['cost']:.5f} |")
        out += [""]

    if "before" in labels and "after" in labels:
        b, a = sums(load("before")), sums(load("after"))
        out += [
            "### Before and after (the same three scenarios, measured twice)", "",
            "| Metric | Current (before) | Optimized (after) | Change |", "|---|---:|---:|---:|",
            f"| Input tokens | {b['prompt']:,} | {a['prompt']:,} | {pct(b['prompt'], a['prompt'])} |",
            f"| Output tokens | {b['completion']:,} | {a['completion']:,} | {pct(b['completion'], a['completion'])} |",
            f"| Total tokens | {b['total']:,} | {a['total']:,} | {pct(b['total'], a['total'])} |",
            f"| Number of LLM calls | {b['calls']} | {a['calls']} | {pct(b['calls'], a['calls'])} |",
            f"| Estimated API cost at Groq list price | ${b['cost']:.5f} | ${a['cost']:.5f} | {pct(b['cost'], a['cost'])} |",
            f"| Summed model time (seconds, calls overlap) | {b['seconds']:.0f} | {a['seconds']:.0f} | {pct(b['seconds'], a['seconds'])} |",
            "",
            ("The runs use a small model with a temperature of 0.2, so two runs never make exactly the same calls (a rewrite more or less changes the count). "
             "Compare the per-call averages in the tables above for the effect of one change, and the totals for the overall effect."),
            "",
        ]
    out += [END]
    return "\n".join(out)


def main() -> int:
    block = build()
    text = DOC.read_text() if DOC.exists() else "# Token usage\n\n" + START + "\n" + END + "\n"
    if START in text and END in text:
        before, rest = text.split(START, 1)
        _, after = rest.split(END, 1)
        text = before + block + after
    else:
        text += "\n" + block + "\n"
    DOC.write_text(text)
    print(f"{DOC.relative_to(ROOT.parent)} updated.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
